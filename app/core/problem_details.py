"""RFC 7807 / RFC 9457 Problem Details for HTTP APIs.

Standard error envelope shared across all RMI services.

Usage:
    from app.core.problem_details import ProblemDetail

    # In a handler:
    return ProblemDetail(
        status=404,
        type_uri="/errors/not_found",
        title="Not Found",
        detail="Post not found",
        instance="/api/v1/bulletin/123",
    ).as_response()

    # Or raise an AppError subclass and let the global handler convert it.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

_STATUS_TITLES: dict[int, str] = {
    400: "Bad Request",
    401: "Unauthorized",
    402: "Payment Required",
    403: "Forbidden",
    404: "Not Found",
    409: "Conflict",
    422: "Unprocessable Entity",
    429: "Too Many Requests",
    500: "Internal Server Error",
    502: "Bad Gateway",
    503: "Service Unavailable",
}


def _default_title(status: int) -> str:
    return _STATUS_TITLES.get(status, "Error")


def _code_to_type(code: str) -> str:
    """Convert dot-notation error code to URI path, e.g. 'auth.invalid_token' → '/errors/auth/invalid_token'."""
    return f"/errors/{code.replace('.', '/')}"


class ProblemDetail(BaseModel):
    """RFC 7807 Problem Details for HTTP APIs.

    See https://datatracker.ietf.org/doc/html/rfc9457 for the spec.
    """

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type",
    )
    title: str = Field(
        default="Error",
        description="Short human-readable summary of the problem",
    )
    status: int = Field(
        default=500,
        ge=400,
        lt=600,
        description="HTTP status code generated by the origin server",
    )
    detail: str = Field(
        default="",
        description="Human-readable explanation specific to this occurrence",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference that identifies the specific occurrence",
    )
    request_id: str | None = Field(
        default=None,
        description="Correlation ID for tracing this request through the system",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="ISO 8601 timestamp of when the error occurred",
    )
    errors: list[dict[str, Any]] | None = Field(
        default=None,
        description="Validation error details (field-level), used primarily for 422 responses",
    )
    code: str | None = Field(
        default=None,
        description="Machine-readable error code (e.g. 'auth.invalid_token')",
    )

    model_config = {"extra": "forbid"}

    def as_response(self, status_: int | None = None) -> JSONResponse:
        """Return a FastAPI JSONResponse with the RFC 7807 body."""
        return JSONResponse(
            status_code=status_ or self.status,
            content=self.model_dump(exclude_none=True),
            media_type="application/problem+json",
        )

    @classmethod
    def create(
        cls,
        status: int,
        detail: str = "",
        *,
        code: str | None = None,
        title: str | None = None,
        instance: str | None = None,
        request_id: str | None = None,
        errors: list[dict[str, Any]] | None = None,
    ) -> ProblemDetail:
        """Convenience constructor with automatic type URI and title resolution."""
        return cls(
            type=_code_to_type(code) if code else "about:blank",
            title=title or _default_title(status),
            status=status,
            detail=detail or _default_title(status),
            instance=instance,
            request_id=request_id,
            errors=errors,
            code=code,
        )


def problem_response(
    status: int,
    code: str,
    detail: str = "",
    instance: str = "",
    errors: list[dict[str, Any]] | None = None,
    request_id: str = "",
) -> JSONResponse:
    """Return a JSONResponse formatted as RFC 7807 Problem Details.

    Legacy helper — prefer constructing a ``ProblemDetail`` model directly.

    Args:
        status: HTTP status code (400–599).
        code: Machine-readable error code (e.g. "auth.invalid_token").
        detail: Human-readable explanation.
        instance: URI of the request that triggered the error.
        errors: Validation error details (for 422).
        request_id: Correlation ID for tracing.
    """
    pd = ProblemDetail.create(
        status=status,
        detail=detail or _default_title(status),
        code=code,
        instance=instance or None,
        request_id=request_id or None,
        errors=errors,
    )
    return pd.as_response()
